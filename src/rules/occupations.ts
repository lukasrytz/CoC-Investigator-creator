import { INTERPERSONAL_SKILL_IDS, type Occupation, type OccupationSkillSlot } from './types'

const interpersonal = (count: number): OccupationSkillSlot => ({
  kind: 'choice',
  count,
  from: INTERPERSONAL_SKILL_IDS,
  label: count === 1 ? 'one interpersonal skill' : `${count} interpersonal skills`,
})

const fixed = (skillId: string, spec?: string): OccupationSkillSlot =>
  spec ? { kind: 'fixed', skillId, spec } : { kind: 'fixed', skillId }

const oneOf = (label: string, ...from: string[]): OccupationSkillSlot => ({
  kind: 'choice',
  count: 1,
  from,
  label,
})

const any = (count: number): OccupationSkillSlot => ({ kind: 'any', count })

