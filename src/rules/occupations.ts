const byId = new Map(OCCUPATIONS.map((o) => [o.id, o]))

export function occupationById(id: string): Occupation {
  const occupation = byId.get(id)
  if (!occupation) throw new Error(`Unknown occupation: ${id}`)
  return occupation
}
